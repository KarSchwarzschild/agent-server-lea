// ─── 基础类型 ───

export type LineStyleType = 'solid' | 'dashed' | 'dotted'

export interface PPTElementShadow {
  h: number
  v: number
  blur: number
  color: string
}

export interface PPTElementOutline {
  style?: LineStyleType
  width?: number
  color?: string
}

export type GradientType = 'linear' | 'radial'
export interface GradientColor {
  pos: number
  color: string
}
export interface Gradient {
  type: GradientType
  colors: GradientColor[]
  rotate: number
}

// ─── 表格 ───

export type TextAlign = 'left' | 'center' | 'right' | 'justify'

export interface TableCellStyle {
  bold?: boolean
  em?: boolean
  underline?: boolean
  strikethrough?: boolean
  color?: string
  backcolor?: string
  fontsize?: string
  fontname?: string
  align?: TextAlign
}

export interface TableCell {
  id: string
  colspan: number
  rowspan: number
  text: string
  style?: TableCellStyle
}

export interface TableTheme {
  color: string
  rowHeader: boolean
  rowFooter: boolean
  colHeader: boolean
  colFooter: boolean
}

// ─── 图表 ───

export type ChartType = 'bar' | 'column' | 'line' | 'pie' | 'ring' | 'area' | 'radar' | 'scatter'

export interface ChartOptions {
  lineSmooth?: boolean
  stack?: boolean
}

export interface ChartData {
  labels: string[]
  legends: string[]
  series: number[][]
}

// ─── PPTSlide 画布类型（OpenMAIC 兼容）───

export interface PPTSlideBackground {
  type: 'solid' | 'gradient' | 'image'
  color?: string
  gradient?: Gradient
  image?: string
  imageSize?: 'cover' | 'contain' | 'repeat'
}

export interface PPTBaseElement {
  id: string
  left: number
  top: number
  width: number
  height: number
  rotate?: number
  opacity?: number
}

export interface PPTTextElement extends PPTBaseElement {
  type: 'text'
  content: string        // HTML content
  defaultFontName: string
  defaultColor: string
  lineHeight?: number
  fill?: string
  outline?: PPTElementOutline
}

export interface PPTImageElement extends PPTBaseElement {
  type: 'image'
  src: string
  fixedRatio: boolean
}

export interface PPTShapeElement extends PPTBaseElement {
  type: 'shape'
  path: string
  viewBox: [number, number]
  fill: string
  fixedRatio: boolean
  outline?: PPTElementOutline
  text?: {
    content: string
    defaultFontName: string
    defaultColor: string
    align?: string
  }
}

export interface PPTLineElement {
  id: string
  type: 'line'
  left: number
  top: number
  width: number          // stroke thickness, NOT length
  start: [number, number]
  end: [number, number]
  style: LineStyleType
  color: string
  points: [string, string]  // ["", "arrow"] etc.
  broken?: [number, number]
  broken2?: [number, number]
  curve?: [number, number]
  cubic?: [[number, number], [number, number]]
  shadow?: PPTElementShadow
}

export interface PPTLatexElement extends PPTBaseElement {
  type: 'latex'
  latex: string
  color: string
  align?: 'left' | 'center' | 'right'
  // path, viewBox, strokeWidth, fixedRatio are auto-generated by system
  path?: string
  viewBox?: [number, number]
  strokeWidth?: number
  fixedRatio?: boolean
}

export interface PPTTableElement extends PPTBaseElement {
  type: 'table'
  colWidths: number[]
  data: TableCell[][]
  outline: PPTElementOutline
  theme?: TableTheme
  cellMinHeight?: number
}

export interface PPTChartElement extends PPTBaseElement {
  type: 'chart'
  chartType: ChartType
  data: ChartData
  themeColors: string[]
  options?: ChartOptions
  fill?: string
  outline?: PPTElementOutline
  textColor?: string
}

export type PPTElement =
  | PPTTextElement
  | PPTImageElement
  | PPTShapeElement
  | PPTLineElement
  | PPTLatexElement
  | PPTTableElement
  | PPTChartElement

export interface PPTSlide {
  background: PPTSlideBackground
  elements: PPTElement[]
}
